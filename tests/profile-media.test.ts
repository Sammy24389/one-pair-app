import {afterEach, expect, it, vi} from 'vitest'
import {inspectProfileVideo, prepareProfileMedia, profileVideoUrl, validProfileMedia} from '../src/lib/profile-media'
const storage = vi.hoisted(() => ({get: vi.fn(), put: vi.fn()}))
vi.mock('../src/lib/idb', () => ({getMedia: storage.get, putMedia: storage.put}))
afterEach(() => {vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.clearAllMocks()})
it('accepts only bounded local profile video references', () => {
  expect(validProfileMedia({id: 'abc123def456gh78', mime: 'video/mp4', size: 20})).toBe(true)
  for (const m of [null, {}, {id: 'https://tracker', mime: 'video/mp4', size: 2}, {id: 'abc123def456gh78', mime: 'image/svg+xml', size: 2}, {id: 'abc123def456gh78', mime: 'video/mp4', size: 6 * 1024 * 1024}]) expect(validProfileMedia(m)).toBe(false)
})
it('rejects unsafe or oversized selections before storing', async () => {
  await expect(prepareProfileMedia(new File(['x'], 'x.svg', {type: 'image/svg+xml'}))).rejects.toThrow('supported image')
  await expect(prepareProfileMedia(new File(['x'], 'x.mov', {type: 'video/quicktime'}))).rejects.toThrow('MP4 or WebM')
  expect(storage.put).not.toHaveBeenCalled()
})
it('validates decoded duration and dimensions and releases metadata URL', async () => {
  const video = document.createElement('video')
  vi.spyOn(document, 'createElement').mockReturnValue(video)
  vi.spyOn(video, 'load').mockImplementation(() => {})
  URL.createObjectURL = vi.fn(() => 'blob:metadata')
  URL.revokeObjectURL = vi.fn()
  Object.defineProperties(video, {duration: {value: 16, configurable: true}, videoWidth: {value: 720, configurable: true}, videoHeight: {value: 1280, configurable: true}})
  const pending = inspectProfileVideo(new Blob(['v'], {type: 'video/mp4'}))
  video.dispatchEvent(new Event('loadedmetadata'))
  await expect(pending).rejects.toThrow('15 seconds')
  expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:metadata')
  Object.defineProperty(video, 'duration', {value: 10})
  const valid = inspectProfileVideo(new Blob(['v'], {type: 'video/mp4'}))
  video.dispatchEvent(new Event('loadedmetadata'))
  await expect(valid).resolves.toBeUndefined()
})
it('checks transferred blob size and MIME before rendering a video URL', async () => {
  const m = {id: 'abc123def456gh78', mime: 'video/mp4', size: 1}
  storage.get.mockResolvedValue({blob: new Blob(['x'], {type: 'image/svg+xml'})})
  expect(await profileVideoUrl(m)).toBe(null)
  storage.get.mockResolvedValue({blob: new Blob(['x'], {type: 'video/mp4'})})
  URL.createObjectURL = vi.fn(() => 'blob:valid')
  expect(await profileVideoUrl(m)).toBe('blob:valid')
})
it('rejects oversized decoded photos and closes bitmaps on preparation failures', async () => {
  const close = vi.fn()
  vi.stubGlobal('createImageBitmap', vi.fn().mockResolvedValue({width: 5000, height: 4000, close}))
  const file = new File(['photo'], 'photo.png', {type: 'image/png'})
  await expect(prepareProfileMedia(file)).rejects.toThrow('16 megapixels')
  expect(close).toHaveBeenCalledTimes(1)
  vi.stubGlobal('createImageBitmap', vi.fn().mockResolvedValue({width: 160, height: 160, close}))
  vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockReturnValue(null)
  await expect(prepareProfileMedia(file)).rejects.toThrow('could not prepare')
  expect(close).toHaveBeenCalledTimes(2)
})
